const countryCodeSet = new Set(volunteerCountryOptions.map((country) => country.code));

function normalizeCountryKey(value: string) {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const countryAliasToCode = new Map<string, string>();

volunteerCountryOptions.forEach((country) => {
  countryAliasToCode.set(normalizeCountryKey(country.code), country.code);
  countryAliasToCode.set(normalizeCountryKey(country.name), country.code);
  country.aliases?.forEach((alias) => {
    countryAliasToCode.set(normalizeCountryKey(alias), country.code);
  });
});

export function parseVolunteerCountryCode(value: unknown) {
  if (typeof value !== "string") return null;

  const trimmed = value.trim();
  if (!trimmed) return null;

  const upperValue = trimmed.toUpperCase();
  if (countryCodeSet.has(upperValue)) return upperValue;

  return countryAliasToCode.get(normalizeCountryKey(trimmed)) || null;
}

export function getVolunteerCountryName(code: string) {
  return volunteerCountryOptions.find((country) => country.code === code)?.name || code;
}

export function isVolunteerCountryCode(value: string) {
  return countryCodeSet.has(value.toUpperCase());
}

export const volunteerCountryCodeSchema = z.preprocess(
  (value) => parseVolunteerCountryCode(value) || value,
  z
    .string()
    .trim()
    .length(2)
    .transform((value) => value.toUpperCase())
    .refine(isVolunteerCountryCode, "Select a valid country.")
);
